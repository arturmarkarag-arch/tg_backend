const mongoose = require('mongoose');

const ReceiptSchema = new mongoose.Schema(
  {
    receiptNumber: { type: String, required: true, unique: true },
    status: { type: String, enum: ['draft', 'completed'], default: 'draft' },
    createdBy: { type: String, required: true },
    assignedTo: { type: String, default: null },
    startedAt: { type: Date, default: Date.now },
    completedAt: { type: Date, default: null },

    // ── Тип накладної ─────────────────────────────────────────────────────────
    // Мета накладної задається ОДИН раз, при створенні, а не збирається з
    // галочок на позиціях (рішення власника 05.08.2026 — заміна поля
    // ReceiptItem.supplementOffer).
    //
    //   'regular'    — звичайне приймання: позиція йде на склад або в магазини,
    //                  жодних пропозицій дозамовлення не виникає;
    //   'supplement' — уся накладна є хвилею дозамовлення: КОЖНА позиція йде на
    //                  склад ('shops' заборонено) і після проведення
    //                  пропонується ОДНІЙ вибраній групі доставки.
    //
    // Чому один тип на накладну, а не прапорець на позиції: «частина позицій —
    // дозамовлення, частина ні» породжувала стан, який неможливо показати
    // одним екраном, і чотири окремі правила скидання прапорця (зміна
    // призначення, редагування чужої позиції, повторне проведення, часткове
    // створення пропозицій).
    type: { type: String, enum: ['regular', 'supplement'], default: 'regular' },

    // ── Ціль хвилі (лише для type='supplement') ───────────────────────────────
    // ОДНА група доставки, обрана людиною в модалці проведення і ЗАФІКСОВАНА в
    // цей момент. Після проведення змінити не можна: уже існують заявки
    // магазинів, Telegram-розсилка і, можливо, спаковані рядки.
    //
    // Сесії тут свідомо НЕМА (рішення власника 05.08.2026, друга ітерація):
    // хвиля дозамовлення живе власним циклом і до OrderingSession не
    // прив'язується — див. models/SupplementOffer.js.
    targetDeliveryGroupId: { type: String, default: null },

    // Дедлайн хвилі рахується ОДИН раз, у момент проведення, і живе тут.
    // Пропозиції беруть його готовим — тому довідновлення напівстворених хвиль
    // (reconcilePendingReceipts) не роздає групам різні дедлайни і не подовжує
    // вікно кожним ретраєм.
    supplementOpenedAt: { type: Date, default: null },
    supplementClosesAt: { type: Date, default: null },

    // ── Дозамовлення: стан відкриття пропозицій після проведення ──────────────
    // Створення пропозицій живе ПОЗА транзакцією проведення (див.
    // services/supplementOffers.createOffersForReceipt), тому між «накладна
    // проведена» і «пропозиції відкриті» є вікно, у якому може впасти Mongo,
    // мережа або сам процес. Без цього маркера така накладна лишалась би
    // назавжди напівобробленою: повторно провести її вже не можна (вона
    // completed), а нічого перевідкрити пропозиції не намагалося.
    //
    //   null    — накладна ще не проведена, або вона не типу 'supplement'
    //   'pending' — проведена, пропозиції ще не створені (або створені не всі)
    //   'ready'   — усі пропозиції створені; звірятель більше її не чіпає
    //
    // Звірятель у services/supplementScheduler.js добиває 'pending' на кожному
    // тіку. Створення ідемпотентне (унікальні індекси), тож повтор безпечний.
    supplementStatus: { type: String, enum: ['pending', 'ready', null], default: null },
  },
  { timestamps: true }
);

// Звірятель шукає саме такі накладні — маленький індекс замість перебору всіх.
ReceiptSchema.index({ supplementStatus: 1 }, { sparse: true });

module.exports = mongoose.model('Receipt', ReceiptSchema);
